    if type(project.boot) == "table" and next(project.boot) then
      out[#out + 1] = string.format(
        "  mod.content.field:patch(%q, %s)",
        "boot", emitTableLiteral(project.boot, 1))
      out[#out + 1] = ""
    end

    for _, key in ipairs({ "title", "intro", "theme", "townMap" }) do
      local rec = project[key]
      if type(rec) == "table" and next(rec) then
        local lit = rewriteModPaths(emitTableLiteral(stripEditorFields(rec), 1))
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)", key, lit)
        out[#out + 1] = ""
      end
    end
  end

  -- font pages
  local fontIds = {}
  for fid in pairs(project.font or {}) do fontIds[#fontIds + 1] = fid end
  table.sort(fontIds)
  for _, fid in ipairs(fontIds) do
    local raw = project.font[fid]
    if type(raw) == "table" then
      local rec = stripEditorFields(raw)
      local verb = emitVerb(raw)
      local lit = rewriteModPaths(emitTableLiteral(rec, 1))
      out[#out + 1] = string.format("  mod.content.font:%s(%q, %s)",
        verb, fid, lit)
      out[#out + 1] = ""
    end
  end

  -- engine Strings() overrides
  local strIds = {}
  for sid in pairs(project.strings or {}) do strIds[#strIds + 1] = sid end
  table.sort(strIds)
  for _, sid in ipairs(strIds) do
    local body = project.strings[sid]
    if type(body) == "string" and body ~= "" then
      out[#out + 1] = string.format("  mod.content.strings:override(%q, %s)",
        sid, escapeStr(body))
    end
  end
  if #strIds > 0 then out[#out + 1] = "" end

  -- Player overworld remaps + battle/intro pics.
  -- Gen1: field.playerSprites / field.playerPics (Schemas.field).
  -- Gold: field is gated; write gen2PlayerSprites + gen2MenuGfx / playerPic.
  if type(project.playerSprites) == "table" then
    local ps = {}
    for k, v in pairs(project.playerSprites) do
      if type(k) == "string" and type(v) == "string" and v ~= "" then
        ps[k] = v
      end
    end
    if next(ps) then
      if gen2 then
        out[#out + 1] = "  -- Gold player state sprites (FieldMoves.spriteId)"
        out[#out + 1] = "  do"
        out[#out + 1] = "    local _ps = " .. emitTableLiteral(ps, 2)
        out[#out + 1] = "    mod.events:on(\"mods.loaded\", function(ev)"
        out[#out + 1] = "      local data = ev and ev.data"
        out[#out + 1] = "      if type(data) ~= \"table\" then return end"
        out[#out + 1] = "      data.gen2PlayerSprites = data.gen2PlayerSprites or {}"
        out[#out + 1] = "      for k, v in pairs(_ps) do data.gen2PlayerSprites[k] = v end"
        out[#out + 1] = "    end)"
        out[#out + 1] = "  end"
        out[#out + 1] = ""
      else
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "playerSprites", emitTableLiteral(ps, 1))
        out[#out + 1] = ""
      end
    end
  end

  if type(project.playerPics) == "table" then
    local pp = {}
    for k, v in pairs(project.playerPics) do
      if type(k) == "string" and type(v) == "string" and v ~= "" then
        pp[k] = v
      end
    end
    if next(pp) then
      local lit = rewriteModPaths(emitTableLiteral(pp, 1))
      if gen2 then
        out[#out + 1] = "  -- Gold player battle / intro pics (gen2MenuGfx + playerPic)"
        out[#out + 1] = "  do"
        out[#out + 1] = "    local _pp = " .. lit
        out[#out + 1] = "    mod.events:on(\"mods.loaded\", function(ev)"
        out[#out + 1] = "      local data = ev and ev.data"
        out[#out + 1] = "      if type(data) ~= \"table\" then return end"
        out[#out + 1] = "      local gfx = data.gen2MenuGfx or data.menu_gfx"
        out[#out + 1] = "      if type(gfx) ~= \"table\" then"
        out[#out + 1] = "        gfx = {}; data.gen2MenuGfx = gfx; data.menu_gfx = gfx"
        out[#out + 1] = "      end"
        out[#out + 1] = "      gfx.battleHud = gfx.battleHud or {}"
        out[#out + 1] = "      if _pp.back then gfx.battleHud.playerBack = _pp.back end"
        out[#out + 1] = "      if _pp.backFemale then gfx.battleHud.playerBackFemale = _pp.backFemale end"
        out[#out + 1] = "      if _pp.demoBack then gfx.battleHud.dudeBack = _pp.demoBack end"
        out[#out + 1] = "      if _pp.front then data.playerPic = _pp.front end"
        out[#out + 1] = "      if _pp.frontFemale then data.playerPicFemale = _pp.frontFemale end"
        out[#out + 1] = "    end)"
        out[#out + 1] = "  end"
        out[#out + 1] = ""
      else
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "playerPics", lit)
        out[#out + 1] = ""
      end
    end
  end

  -- Gen1 field.* buckets (Schemas.GEN2.field = false — drop on Gold).
  if not gen2 then
    -- field.ledges (deep-merge lists append; emit only author-added rows)
    if type(project.ledges) == "table" and #project.ledges > 0 then
      local rows = {}
      for _, ledge in ipairs(project.ledges) do
        if type(ledge) == "table" then
          rows[#rows + 1] = stripEditorFields(ledge)
        end
      end
      if #rows > 0 then
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "ledges", emitTableLiteral(rows, 1))
        out[#out + 1] = ""
      end
    end

    -- field.hiddenItems
    if type(project.hiddenItems) == "table" and next(project.hiddenItems) then
      out[#out + 1] = string.format(
        "  mod.content.field:patch(%q, %s)",
        "hiddenItems", emitTableLiteral(project.hiddenItems, 1))
      out[#out + 1] = ""
    end

    -- field.badgeGates (false = suppress / DELETE so deep-merge removes it)
    if type(project.badgeGates) == "table" then
      local gates, gateDelete = {}, {}
      for mid, gate in pairs(project.badgeGates) do
        if gate == false then
          gateDelete[#gateDelete + 1] = mid
        elseif type(gate) == "table" then
          gates[mid] = stripEditorFields(gate)
        end
      end
      if next(gates) then
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "badgeGates", emitTableLiteral(gates, 1))
        out[#out + 1] = ""
      end
      table.sort(gateDelete)
      for _, mid in ipairs(gateDelete) do
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, { [%q] = mod.DELETE })",
          "badgeGates", mid)
        out[#out + 1] = ""
      end
    end

    -- field.darkMaps (maps that need FLASH until lit)
    if type(project.darkMaps) == "table" and type(project.darkMaps.maps) == "table" then
      local dm = { maps = {} }
      for i, mid in ipairs(project.darkMaps.maps) do
        if type(mid) == "string" and mid ~= "" then
          dm.maps[#dm.maps + 1] = mid
        end
      end
      if type(project.darkMaps.palOffset) == "number" then
        dm.palOffset = project.darkMaps.palOffset
      end
      out[#out + 1] = string.format(
        "  mod.content.field:patch(%q, %s)",
        "darkMaps", emitTableLiteral(dm, 1))
      out[#out + 1] = ""
    end
  end

  -- Gen1 field.trades / Gold npc_trades (events.lua NPC trade rows)
  if type(project.trades) == "table" and #project.trades > 0 then
    if gen2 then
      for i, t in ipairs(project.trades) do
        if type(t) == "table" and t.give and t.get then
          local id = t.id
          if id == nil then id = i - 1 end
          local row = {
            id = id,
            dialog = t.dialog,
            give = t.give,
            get = t.get,
            giveIndex = t.giveIndex,
            getIndex = t.getIndex,
            nickname = t.nickname,
            dvs = type(t.dvs) == "table" and {
              tonumber(t.dvs[1]) or 0, tonumber(t.dvs[2]) or 0,
            } or nil,
            item = t.item,
            otId = tonumber(t.otId) or 0,
            otName = t.otName,
            gender = t.gender,
          }
          out[#out + 1] = string.format(
            "  mod.content.npc_trades:override(%q, %s)",
            tostring(id), emitTableLiteral(row, 1))
          out[#out + 1] = ""
        end
      end
    else
      local rows = {}
      for _, t in ipairs(project.trades) do
        if type(t) == "table" and t.give and t.get then
          rows[#rows + 1] = {
            give = t.give, get = t.get,
            dialogset = tonumber(t.dialogset) or 1,
            nickname = t.nickname,
          }
        end
      end
      if #rows > 0 then
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "trades", emitTableLiteral(rows, 1))
        out[#out + 1] = ""
      end
    end
  end

  -- field.flyOrder / field.flyWarps (Gen1 Town Map + Fly; gated on Gold)
  if not gen2 then
    if type(project.flyOrder) == "table" and #project.flyOrder > 0 then
      local order = {}
      for _, mid in ipairs(project.flyOrder) do
        if type(mid) == "string" and mid ~= "" then
          order[#order + 1] = mid
        end
      end
      if #order > 0 then
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "flyOrder", emitTableLiteral(order, 1))
        out[#out + 1] = ""
      end
    end
    if type(project.flyWarps) == "table" and next(project.flyWarps) then
      local warps = {}
      for mid, spot in pairs(project.flyWarps) do
        if type(mid) == "string" and type(spot) == "table" then
          warps[mid] = {
            x = tonumber(spot.x) or 0,
            y = tonumber(spot.y) or 0,
          }
        end
      end
      if next(warps) then
        out[#out + 1] = string.format(
          "  mod.content.field:patch(%q, %s)",
          "flyWarps", emitTableLiteral(warps, 1))
        out[#out + 1] = ""
      end
    end
  end

  -- Gold fly points: gen2Landmarks.spawns landing coords. FieldMoves has
  -- no setFlyPoints; SPAWN_HOME is also copied to SPAWN_NEW_BARK.
  if gen2 and type(project.flyPoints) == "table" and #project.flyPoints > 0 then
    local rows, spawns = {}, {}
    for _, row in ipairs(project.flyPoints) do
      if type(row) == "table" and type(row.landmark) == "string" and row.landmark ~= ""
          and type(row.spawn) == "string" and row.spawn ~= "" then
        rows[#rows + 1] = {
          landmark = row.landmark, spawn = row.spawn,
          flag = tonumber(row.flag) or 0,
        }
        if type(row.map) == "string" and row.map ~= "" then
          spawns[row.spawn] = {
            map = row.map, x = tonumber(row.x) or 0, y = tonumber(row.y) or 0,
          }
        end
      end
    end
    if #rows > 0 then
      out[#out + 1] = "  -- Gold fly points (gen2Landmarks.spawns)"
      out[#out + 1] = "  do"
      out[#out + 1] = "    local _flySpawns = " .. emitTableLiteral(spawns, 1)
      out[#out + 1] = "    mod.events:on(\"mods.loaded\", function(ev)"
      out[#out + 1] = "      local data = ev and ev.data"
      out[#out + 1] = "      if type(data) ~= \"table\" then return end"
      out[#out + 1] = "      local lm = data.gen2Landmarks or data.landmarks"
      out[#out + 1] = "      if type(lm) ~= \"table\" then return end"
      out[#out + 1] = "      lm.spawns = lm.spawns or {}"
      out[#out + 1] = "      for spawnId, spot in pairs(_flySpawns) do"
      out[#out + 1] = "        lm.spawns[spawnId] = spot"
      out[#out + 1] = "      end"
      out[#out + 1] = "      if lm.spawns.SPAWN_HOME and not lm.spawns.SPAWN_NEW_BARK then"
      out[#out + 1] = "        lm.spawns.SPAWN_NEW_BARK = lm.spawns.SPAWN_HOME"
      out[#out + 1] = "      end"
      out[#out + 1] = "    end)"
      out[#out + 1] = "  end"
      out[#out + 1] = ""
    end
  end

  -- Lab starter remap (pokemon.before_give): Oak on Gen1, Elm on Gold.
  local remap = project.starterRemap
  if type(remap) == "table" and next(remap) then
    local has = false
    for _, to in pairs(remap) do
      if type(to) == "table" and to.species and to.species ~= "" then
        has = true; break
      elseif type(to) == "string" and to ~= "" then
        has = true; break
      end
    end
    if has then
      local labMap = gen2 and "ELMS_LAB" or "OAKS_LAB"
      out[#out + 1] = "  do"
      out[#out + 1] = "    local remap = {"
      local keys = {}
      for from in pairs(remap) do keys[#keys + 1] = from end
      table.sort(keys)
      for _, from in ipairs(keys) do
        local to = remap[from]
        local sp, lv
        if type(to) == "table" then
          sp, lv = to.species, tonumber(to.level) or 5
        else
          sp, lv = to, 5
        end
        if sp and sp ~= "" then
          out[#out + 1] = string.format(
            "      [%q] = { species = %q, level = %d },", from, sp, lv)
        end
      end
      out[#out + 1] = "    }"
      out[#out + 1] = "    mod.events:on(\"pokemon.before_give\", function(gift)"
      out[#out + 1] = "      local ctx = gift.ctx or {}"
      out[#out + 1] = "      local map = ctx.overworld and ctx.overworld.map"
      out[#out + 1] = "      local mapId = ctx.mapId or (map and map.id)"
      out[#out + 1] = string.format(
        "      if mapId ~= %q then return end", labMap)
      if not gen2 then
        out[#out + 1] = "      local save = ctx.save or (ctx.game and ctx.game.save)"
        out[#out + 1] = "      if save and save.flags and save.flags.EVENT_GOT_STARTER then return end"
      end
      out[#out + 1] = "      local hit = remap[gift.species]"
      out[#out + 1] = "      if not hit then return end"
      out[#out + 1] = "      gift.species = hit.species"
      out[#out + 1] = "      gift.level = hit.level"
      out[#out + 1] = "    end)"
      out[#out + 1] = "  end"
      out[#out + 1] = ""
    end
  end

  -- Gold shiny encounter rate (denominator).  Engine reads data.shinyRate in
  -- Mon.rollEncounterDVs; unset keeps cart DV-pattern odds (~1/8192).
  if gen2 and tonumber(project.shinyRate) and tonumber(project.shinyRate) >= 1 then
    local rate = math.floor(tonumber(project.shinyRate))
    out[#out + 1] = "  -- Shiny encounter rate (1 / N; Mon.rollEncounterDVs)"
    out[#out + 1] = "  do"
    out[#out + 1] = string.format("    local shinyRate = %d", rate)
    out[#out + 1] = "    mod.events:on(\"mods.loaded\", function(ev)"
    out[#out + 1] = "      local data = ev and ev.data"
    out[#out + 1] = "      if type(data) == \"table\" then data.shinyRate = shinyRate end"
    out[#out + 1] = "    end)"
    out[#out + 1] = "  end"
    out[#out + 1] = ""
  end

  -- Gold Day-Care / breeding knobs (data.breeding → Breeding.knobs).
  if gen2 and type(project.breeding) == "table" and next(project.breeding) then
    local lit = emitTableLiteral(project.breeding, 2)
    out[#out + 1] = "  -- Day-Care / breeding overrides (Breeding.knobs)"
    out[#out + 1] = "  do"
    out[#out + 1] = "    local breeding = " .. lit
    out[#out + 1] = "    mod.events:on(\"mods.loaded\", function(ev)"
    out[#out + 1] = "      local data = ev and ev.data"
    out[#out + 1] = "      if type(data) ~= \"table\" then return end"
    out[#out + 1] = "      data.breeding = data.breeding or {}"
    out[#out + 1] = "      for k, v in pairs(breeding) do data.breeding[k] = v end"
    out[#out + 1] = "    end)"
    out[#out + 1] = "  end"
    out[#out + 1] = ""
  end

  -- Stock Gen1Recomp: map index >= firstIndoorMap (37) rolls wilds on EVERY
  -- tile (terrain "indoor"), unless the tileset is FOREST.  Content-editor
  -- Outside maps often use index 1000+.  Suppress those indoor rolls from the
  -- mod so grass/water-only behavior works without patching the game install.
  -- Gold has no firstIndoorMap indoor-wild rule — skip on Gen 2.
  if not gen2 then
    local outsideIds = {}
    for _, mid in ipairs(mIds) do
      local m = project.maps[mid]
      if type(m) == "table" then
        local env = m.environment
        local outside = false
        if env == "outside" then
          outside = true
        elseif env ~= "inside" and env ~= "cave" then
          if m.outdoor == true then
            outside = true
          elseif m.outdoor ~= false then
            local ts = m.tileset
            outside = (ts == "OVERWORLD" or ts == "PLATEAU")
          end
        end
        if outside then outsideIds[#outsideIds + 1] = mid end
      end
    end
    if #outsideIds > 0 then
      out[#out + 1] = "  -- Outside maps: block stock every-tile indoor wilds (index >= 37)"
      out[#out + 1] = "  do"
      out[#out + 1] = "    local outsideMaps = {"
      for _, mid in ipairs(outsideIds) do
        out[#out + 1] = string.format("      [%q] = true,", mid)
      end
      out[#out + 1] = "    }"
      out[#out + 1] = "    mod.hooks:wrap(\"encounter.roll\", function(next, encDef, ctx)"
      out[#out + 1] = "      if ctx and ctx.terrain == \"indoor\" and ctx.mapId"
      out[#out + 1] = "         and outsideMaps[ctx.mapId] then"
      out[#out + 1] = "        return nil"
      out[#out + 1] = "      end"
      out[#out + 1] = "      return next(encDef, ctx)"
      out[#out + 1] = "    end)"
      out[#out + 1] = "  end"
      out[#out + 1] = ""
    end
  end

  out[#out + 1] = "end"
  out[#out + 1] = ""
  return table.concat(out, "\n")
end

local function specialTrainerId(specId)
  return "OPP_SPEC_" .. tostring(specId)
end

local function projectMapLabel(project, mapId)
  local m = project.maps and project.maps[mapId]
  if m and type(m.label) == "string" and m.label ~= "" then return m.label end
  if type(mapId) ~= "string" or mapId == "" then return "Map" end
  return (mapId:lower():gsub("_(%w)", function(c) return c:upper() end)
    :gsub("^%w", string.upper))
end

-- Ensure every trainer object has a trainer_headers row, and wire Special
-- battle encounters (bind TEXT_*) as real overworld trainers (trainerClass +
-- headers).  Without headers, engageTrainer has no beat flag / won text.
function ModWriter.ensureTrainerHeaders(project)
  if type(project) ~= "table" then return end
  local State = require("State")
  project.trainer_headers = project.trainer_headers or {}
  project.text = project.text or {}
  project.eventFlags = project.eventFlags or {}

  for mapId, map in pairs(project.maps or {}) do
    if type(map) == "table" then
      local label = projectMapLabel(project, mapId)
      for i, obj in ipairs(map.objects or {}) do
        if type(obj) == "table" and obj.trainerClass and obj.trainerClass ~= "" then
          local idx = obj.index or i
          project.trainer_headers[label] = project.trainer_headers[label] or {}
          local bucket = project.trainer_headers[label]
          if type(bucket[idx]) ~= "table" then
            local base = "_" .. mapId .. "Trainer" .. idx
            local beat = State.modFlag(project, "BEAT_" .. mapId .. "_" .. idx)
            project.eventFlags[beat] = true
            bucket[idx] = {
              range = 2,
              battle = base .. "Battle",
              won = base .. "Won",
              after = base .. "After",
              event = beat,
              opponent = obj.trainerClass,
              party = tonumber(obj.trainerParty) or 1,
            }
            project.text[base .. "Battle"] = project.text[base .. "Battle"]
              or "Let's fight!"
            project.text[base .. "Won"] = project.text[base .. "Won"] or "I lost..."
            project.text[base .. "After"] = project.text[base .. "After"]
              or "You're strong."
          else
            bucket[idx].opponent = obj.trainerClass
            bucket[idx].party = tonumber(obj.trainerParty)
              or bucket[idx].party or 1
          end
        end
      end
    end
  end

  for sid, spec in pairs(project.specialEncounters or {}) do
    if type(spec) == "table"
        and (spec.kind or "gift") == "battle"
        and type(spec.mapId) == "string" and spec.mapId ~= ""
        and type(spec.bindTextId) == "string" and spec.bindTextId ~= "" then
      local map = project.maps and project.maps[spec.mapId]
      if type(map) == "table" then
        for i, obj in ipairs(map.objects or {}) do
          if type(obj) == "table" and obj.text == spec.bindTextId then
            local idx = obj.index or i
            local tid = specialTrainerId(sid)
            local label = projectMapLabel(project, spec.mapId)
            local base = "_" .. spec.mapId .. "Trainer" .. idx
            local beat = State.modFlag(project,
              (spec.flag and spec.flag ~= "" and spec.flag)
                or ("BEAT_" .. sid))
            project.eventFlags[beat] = true
            obj.trainerClass = tid
            obj.trainerParty = 1
            project.text[base .. "Battle"] = spec.text or "Let's fight!"
            project.text[base .. "Won"] = spec.won or "I lost..."
            project.text[base .. "After"] = spec.after or "You're strong."
            project.trainer_headers[label] = project.trainer_headers[label] or {}
            project.trainer_headers[label][idx] = {
              range = tonumber(spec.range) or 2,
              battle = base .. "Battle",
              won = base .. "Won",
              after = base .. "After",
              event = beat,
              opponent = tid,
              party = 1,
            }
          end
        end
      end
    end
  end

  -- Drop headers / battle text / beat flags for object indices that no longer
  -- exist (delete-object used to leave them in main.lua).
  local live = {}
  for mapId, map in pairs(project.maps or {}) do
    if type(map) == "table" then
      local label = projectMapLabel(project, mapId)
      live[label] = live[label] or {}
      for i, obj in ipairs(map.objects or {}) do
        if type(obj) == "table" and obj.trainerClass and obj.trainerClass ~= "" then
          live[label][obj.index or i] = true
        end
      end
    end
  end
  for label, bucket in pairs(project.trainer_headers) do
    if type(bucket) == "table" then
      local drop = {}
      for idx, hdr in pairs(bucket) do
        if type(idx) == "number" and type(hdr) == "table"
            and not (live[label] and live[label][idx]) then
          drop[#drop + 1] = idx
        end
      end
      for _, idx in ipairs(drop) do
        local hdr = bucket[idx]
        for _, key in ipairs({ "battle", "won", "after" }) do
          local tid = hdr[key]
          if type(tid) == "string" and tid ~= "" then
            project.text[tid] = nil
          end
        end
        if type(hdr.event) == "string" and hdr.event ~= "" then
          project.eventFlags[hdr.event] = nil
        end
        bucket[idx] = nil
      end
      if not next(bucket) then
        project.trainer_headers[label] = nil
      end
    end
  end
end

local function specialMonSlot(spec)
  local slot = {
    species = spec.species or "MAGIKARP",
    level = tonumber(spec.level) or 5,
  }
  if type(spec.moves) == "table" and #spec.moves > 0 then
    local moves = {}
    for i = 1, math.min(4, #spec.moves) do
      local mid = spec.moves[i]
      if type(mid) == "string" and mid ~= "" then
        moves[#moves + 1] = mid
      end
    end
    if #moves > 0 then slot.moves = moves end
  end
  if type(spec.dvs) == "table" then
    local dvs, any = {}, false
    for _, k in ipairs({ "attack", "defense", "speed", "special", "hp" }) do
      local n = tonumber(spec.dvs[k])
      if n ~= nil then
        dvs[k] = math.max(0, math.min(15, math.floor(n)))
        any = true
      end
    end
    if any then slot.dvs = dvs end
  end
  return slot
end

