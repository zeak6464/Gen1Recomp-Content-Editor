-- Vanilla maps.blocks is 0..255 (ROM byte). Layered true-color maps index
-- unique 16x16 cells, so allow any non-negative block id. Width/height are
-- also unbounded (the ROM header was a byte; mods are not).
function ModWriter.mapsNeedWideBlocks(project)
  for _, map in pairs((project and project.maps) or {}) do
    if type(map) == "table" then
      if (tonumber(map.width) or 0) > 255
          or (tonumber(map.height) or 0) > 255 then
        return true
      end
      local blocks = map.blocks
      if type(blocks) == "table" then
        for i = 1, #blocks do
          local n = blocks[i]
          if type(n) == "number" and (n > 255 or n < 0) then return true end
        end
      end
    end
  end
  return false
end

